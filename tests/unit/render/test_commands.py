"""Commands: a prompt per workflow command for the clients that have a `/` menu."""

from __future__ import annotations

import pytest

from orqlet.adapters.clients.claude_code import ClaudeCodeAdapter
from orqlet.adapters.clients.codex import CodexAdapter
from orqlet.adapters.clients.cursor import CursorAdapter
from orqlet.adapters.render.rules import claude_command, cursor_command
from orqlet.application.ports.instruction_adapter import ClientCommand
from orqlet.application.usecases.render_request import RenderRequestError, parse_command
from orqlet.domain.ownership import FileClass, OwnerMode
from tests.support.render import COMMAND_NAMES, packaged_request

pytestmark = pytest.mark.unit

COMMAND = ClientCommand(
    name="sample",
    description="A sample: with a colon",
    body="Do the thing.\n",
    inputs=(("commands/sample", "0.1.0", "a" * 64),),
)


def test_the_package_ships_the_expected_commands_in_name_order() -> None:
    assert tuple(c.name for c in packaged_request().commands) == COMMAND_NAMES


def test_every_command_names_the_orqlet_command_it_runs_and_has_a_one_line_description() -> None:
    for command in packaged_request().commands:
        assert "`orqlet " in command.body, command.name
        assert command.description, command.name
        assert "\n" not in command.description, command.name


def test_claude_gets_a_description_and_cursor_gets_plain_markdown() -> None:
    claude = claude_command(COMMAND)
    cursor = cursor_command(COMMAND)

    assert str(claude.path) == ".claude/commands/orqlet-sample.md"
    assert claude.content.startswith(b'---\ndescription: "A sample: with a colon"\n---\n')
    assert str(cursor.path) == ".cursor/commands/orqlet-sample.md"
    assert cursor.content.startswith(b"<!-- Generated by Orqlet.")  # no front matter
    assert claude.content.endswith(b"Do the thing.\n")
    assert cursor.content.endswith(b"Do the thing.\n")


def test_commands_are_generated_files_that_orqlet_owns_and_records_their_inputs() -> None:
    for rendered in (claude_command(COMMAND), cursor_command(COMMAND)):
        assert rendered.owner is OwnerMode.ORQLET
        assert rendered.file_class is FileClass.GENERATED
        assert rendered.inputs == COMMAND.inputs


@pytest.mark.parametrize("name", ["", "Upper", "with space", "../x", "-lead"])
def test_a_bad_command_name_is_refused(name: str) -> None:
    bad = ClientCommand(name=name, description="d", body="b")

    with pytest.raises(ValueError, match="command file name"):
        claude_command(bad)
    with pytest.raises(ValueError, match="command file name"):
        cursor_command(bad)


def test_codex_has_no_commands_and_says_so() -> None:
    result = CodexAdapter().render(packaged_request())

    assert "ORQ-L003" in {limit.code for limit in result.limits}
    assert not [f for f in result.files if "commands" in str(f.path)]


def test_clients_with_a_slash_menu_do_not_report_the_codex_limit() -> None:
    for adapter in (ClaudeCodeAdapter(), CursorAdapter()):
        assert "ORQ-L003" not in {limit.code for limit in adapter.render(packaged_request()).limits}


def test_a_command_source_is_split_into_description_and_body() -> None:
    description, body = parse_command(
        "commands/x.md", "---\ndescription: Hello there\n---\nBody\nmore\n"
    )

    assert (description, body) == ("Hello there", "Body\nmore\n")


@pytest.mark.parametrize(
    "text",
    [
        "no front matter\n",
        "---\ntitle: x\n---\nbody\n",
        "---\ndescription:   \n---\nbody\n",
        "---\ndescription: x\nbody\n",
        "",
    ],
)
def test_a_malformed_command_source_is_a_release_defect_and_is_refused(text: str) -> None:
    with pytest.raises(RenderRequestError, match=r"commands/x\.md"):
        parse_command("commands/x.md", text)
