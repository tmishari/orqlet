"""Role definitions as subagent files (proposal 10.1 and 17.12.5).

A role file names no vendor model of its own: `model: inherit` leaves the choice to the developer.
The one exception is a model that the team's policy assigned (`ClientRole.model_settings`): each
writer below reads only its own client's entry and writes that client's own field. A read-only role
is read-only by the strongest control each client documents: a tool allow-list in Claude Code,
`readonly: true` in Cursor and `sandbox_mode = "read-only"` in Codex.
"""

from __future__ import annotations

from orqlet.adapters.render.emit import front_matter, normalise_text, toml_table
from orqlet.adapters.render.instructions import GENERATED_NOTICE
from orqlet.application.ports.instruction_adapter import ClientRole, ModelSetting, RenderedFile
from orqlet.domain.model_identity import cursor_plain_id
from orqlet.domain.ownership import FileClass, OwnerMode
from orqlet.domain.paths import CanonicalPath

READ_ONLY_TOOLS = "Read, Grep, Glob"
CLAUDE_CODE = "claude-code"
CURSOR = "cursor"
CODEX = "codex"
INHERIT = "inherit"
_TOML_NOTICE = "# Generated by Orqlet. Do not edit by hand; see .orqlet/generated.lock.yaml.\n"


def claude_role(role: ClientRole) -> RenderedFile:
    setting = role.model_settings.get(CLAUDE_CODE)
    fields: list[tuple[str, str | bool]] = [
        ("name", role.name),
        ("description", role.description),
    ]
    if role.read_only:
        fields.append(("tools", READ_ONLY_TOOLS))
    fields.append(("model", INHERIT if setting is None else setting.name))
    if setting is not None and setting.effort is not None:
        fields.append(("effort", setting.effort))
    return _file(f".claude/agents/{role.name}.md", _markdown(fields, role), role)


def cursor_role(role: ClientRole) -> RenderedFile:
    fields: list[tuple[str, str | bool]] = [
        ("name", role.name),
        ("description", role.description),
        ("model", _cursor_model(role.model_settings.get(CURSOR))),
        ("readonly", role.read_only),
    ]
    return _file(f".cursor/agents/{role.name}.md", _markdown(fields, role), role)


def codex_role(role: ClientRole) -> RenderedFile:
    setting = role.model_settings.get(CODEX)
    fields: list[tuple[str, str]] = [("name", role.name), ("description", role.description)]
    if role.read_only:
        fields.append(("sandbox_mode", "read-only"))
    if setting is not None:
        fields.append(("model", setting.name))
        if setting.effort is not None:
            fields.append(("model_reasoning_effort", setting.effort))
    fields.append(("developer_instructions", normalise_text(role.body)))
    return _file(f".codex/agents/{role.name}.toml", _TOML_NOTICE + toml_table(fields), role)


def _cursor_model(setting: ModelSetting | None) -> str:
    """A Cursor `model` value, which is plain text or `inherit`.

    Cursor once read the quotes of a front-matter `name` literally, and its bracketed options are
    unverified, so a value is written only when it needs no quotes and carries no option or effort
    (ADR-003 decision 3). The selection already refuses the other cases with a finding; this is
    the last check before the bytes.
    """
    if setting is None or setting.effort is not None or not cursor_plain_id(setting.name):
        return INHERIT
    return setting.name


def _markdown(fields: list[tuple[str, str | bool]], role: ClientRole) -> str:
    head = front_matter(fields, plain_when_safe=True)
    return f"{head}{GENERATED_NOTICE}\n\n{normalise_text(role.body)}"


def _file(path: str, text: str, role: ClientRole) -> RenderedFile:
    return RenderedFile(
        path=CanonicalPath.parse(path),
        content=text.encode("utf-8"),
        owner=OwnerMode.ORQLET,
        file_class=FileClass.PROTECTED,
        inputs=role.inputs,
    )
