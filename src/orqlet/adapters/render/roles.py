"""Role definitions as subagent files (proposal 10.1 and 17.12.5).

A role file never names a vendor model: `model: inherit` leaves the choice to the developer. A
read-only role is read-only by the strongest control each client documents: a tool allow-list in
Claude Code, `readonly: true` in Cursor and `sandbox_mode = "read-only"` in Codex.
"""

from __future__ import annotations

from orqlet.adapters.render.emit import front_matter, normalise_text, toml_table
from orqlet.adapters.render.instructions import GENERATED_NOTICE
from orqlet.application.ports.instruction_adapter import ClientRole, RenderedFile
from orqlet.domain.ownership import FileClass, OwnerMode
from orqlet.domain.paths import CanonicalPath

READ_ONLY_TOOLS = "Read, Grep, Glob"
_TOML_NOTICE = "# Generated by Orqlet. Do not edit by hand; see .orqlet/generated.lock.yaml.\n"


def claude_role(role: ClientRole) -> RenderedFile:
    fields: list[tuple[str, str | bool]] = [
        ("name", role.name),
        ("description", role.description),
    ]
    if role.read_only:
        fields.append(("tools", READ_ONLY_TOOLS))
    fields.append(("model", "inherit"))
    return _file(f".claude/agents/{role.name}.md", _markdown(fields, role), role)


def cursor_role(role: ClientRole) -> RenderedFile:
    fields: list[tuple[str, str | bool]] = [
        ("name", role.name),
        ("description", role.description),
        ("model", "inherit"),
        ("readonly", role.read_only),
    ]
    return _file(f".cursor/agents/{role.name}.md", _markdown(fields, role), role)


def codex_role(role: ClientRole) -> RenderedFile:
    fields: list[tuple[str, str]] = [("name", role.name), ("description", role.description)]
    if role.read_only:
        fields.append(("sandbox_mode", "read-only"))
    fields.append(("developer_instructions", normalise_text(role.body)))
    return _file(f".codex/agents/{role.name}.toml", _TOML_NOTICE + toml_table(fields), role)


def _markdown(fields: list[tuple[str, str | bool]], role: ClientRole) -> str:
    return f"{front_matter(fields)}{GENERATED_NOTICE}\n\n{normalise_text(role.body)}"


def _file(path: str, text: str, role: ClientRole) -> RenderedFile:
    return RenderedFile(
        path=CanonicalPath.parse(path),
        content=text.encode("utf-8"),
        owner=OwnerMode.ORQLET,
        file_class=FileClass.PROTECTED,
        inputs=role.inputs,
    )
