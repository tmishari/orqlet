"""Workflow skills as each client reads them (proposal 12.4 and 17.10).

Claude Code reads `.claude/skills/<name>/SKILL.md`. Cursor and Codex both read
`.agents/skills/<name>/SKILL.md`, so the file is the same for both and `merge_rendered` keeps one.
A phase skill is started by the person only: Claude Code and Cursor document the field
`disable-model-invocation`, and Codex documents `allow_implicit_invocation: false` in a sidecar
`agents/openai.yaml`.
"""

from __future__ import annotations

from orqlet.adapters.render.emit import front_matter, normalise_text, yaml_document
from orqlet.adapters.render.instructions import GENERATED_NOTICE
from orqlet.application.ports.instruction_adapter import ClientSkill, RenderedFile
from orqlet.domain.digest import sha256_hex
from orqlet.domain.ownership import FileClass, OwnerMode
from orqlet.domain.paths import CanonicalPath

CLAUDE_SKILLS = ".claude/skills"
AGENTS_SKILLS = ".agents/skills"


def claude_skill_files(skill: ClientSkill) -> tuple[RenderedFile, ...]:
    return _skill_files(CLAUDE_SKILLS, skill)


def agents_skill_files(skill: ClientSkill) -> tuple[RenderedFile, ...]:
    """The files Cursor and Codex read. Identical for both clients."""
    return _skill_files(AGENTS_SKILLS, skill)


def codex_sidecar(skill: ClientSkill) -> RenderedFile:
    """`agents/openai.yaml`: Codex will not start the skill from a prompt, only on `$name`."""
    text = "# Generated by Orqlet. Do not edit by hand; see .orqlet/generated.lock.yaml.\n"
    text += yaml_document({"policy": {"allow_implicit_invocation": False}})
    return _file(
        f"{AGENTS_SKILLS}/{skill.name}/agents/openai.yaml",
        text,
        ((f"{skill.name}-codex-policy", "1", sha256_hex(text.encode("utf-8"))),),
    )


def _skill_files(base: str, skill: ClientSkill) -> tuple[RenderedFile, ...]:
    head = front_matter(
        [
            ("name", skill.name),
            ("description", skill.description),
            ("disable-model-invocation", True),
        ],
        plain_when_safe=True,
    )
    text = f"{head}{GENERATED_NOTICE}\n\n{normalise_text(skill.body)}"
    files = [_file(f"{base}/{skill.name}/SKILL.md", text, skill.inputs)]
    for name, content in skill.references:
        reference = f"{GENERATED_NOTICE}\n\n{normalise_text(content)}"
        digest = sha256_hex(reference.encode("utf-8"))
        files.append(
            _file(
                f"{base}/{skill.name}/references/{name}",
                reference,
                ((f"skills/{skill.name}/references/{name}", skill.inputs[0][1], digest),),
            )
        )
    return tuple(files)


def _file(path: str, text: str, inputs: tuple[tuple[str, str, str], ...]) -> RenderedFile:
    return RenderedFile(
        path=CanonicalPath.parse(path),
        content=text.encode("utf-8"),
        owner=OwnerMode.ORQLET,
        file_class=FileClass.PROTECTED,
        inputs=inputs,
    )
